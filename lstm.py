class SNOTELDataset(Dataset):
    def __init__(self, df, feature_cols, target_col, seq_length=90):

        total_samples = 0
        for _, station_df in df.groupby('station'):
            if len(station_df) >= seq_length:
                total_samples += (len(station_df) - seq_length)

        # 2. Pre-allocate the memory
        num_features = len(feature_cols)
        self.X = torch.zeros((total_samples, seq_length, num_features), dtype=torch.float32)
        self.y = torch.zeros((total_samples, 1), dtype=torch.float32)

        print(f"Allocated memory for {total_samples} samples...")


        idx = 0
        for _, station_df in df.groupby('station'):
            station_df = station_df.sort_values('time')
            X_data = station_df[feature_cols].values
            y_data = station_df[target_col].values

            if len(station_df) < seq_length:
                continue

            for i in range(len(station_df) - seq_length):
                self.X[idx] = torch.tensor(X_data[i : i + seq_length], dtype=torch.float32)
                self.y[idx] = torch.tensor(y_data[i + seq_length], dtype=torch.float32)
                idx += 1

        print(f"Final Tensor Shape: {self.X.shape}")

    def __len__(self):
        return len(self.X)

    def __getitem__(self, idx):
        return self.X[idx], self.y[idx]

class SWELSTM(nn.Module):
    def __init__(self, input_dim, hidden_dim=64, num_layers=2, dropout=0.3):
        super(SWELSTM, self).__init__()

        #[Batch, Sequence, Feature]
        self.lstm = nn.LSTM(input_dim, hidden_dim, num_layers,
                            batch_first=True, dropout=dropout)


        self.linear = nn.Linear(hidden_dim, 1)


    def forward(self, x):
        #[batch, sequence, hidden_dim]
        out, _ = self.lstm(x)


        last_day_memory = out[:, -1, :]

        predictions = (self.linear(last_day_memory))
        return predictions

def evaluate_and_calculate(model, loader, device):
    model.eval()

    # R2 and KGE

    sum_y = 0.0
    sum_y_hat = 0.0
    sum_sq_y = 0.0
    sum_sq_y_hat = 0.0
    sum_y_y_hat = 0.0 # for correlation
    count = 0
    sum_sq_err = 0.0 # for MSE/R2 numerator

    with torch.no_grad():
        for X, y in loader:
            X, y = X.to(device), y.to(device)
            preds = model(X)

            p = preds.cpu().numpy().flatten()
            t = y.cpu().numpy().flatten()

            sum_y += np.sum(t)
            sum_y_hat += np.sum(p)
            sum_sq_y += np.sum(t**2)
            sum_sq_y_hat += np.sum(p**2)
            sum_y_y_hat += np.sum(t * p)
            sum_sq_err += np.sum((t - p)**2)
            count += len(t)

    #  means
    mu_y = sum_y / count
    mu_y_hat = sum_y_pred = sum_y_hat / count

    # Standard Deviations
    var_y = (sum_sq_y / count) - (mu_y**2)
    var_y_hat = (sum_sq_y_hat / count) - (mu_y_hat**2)
    std_y = np.sqrt(max(var_y, 1e-8))
    std_y_hat = np.sqrt(max(var_y_hat, 1e-8))

    # R2
    ss_res = sum_sq_err
    ss_tot = var_y * count
    r2 = 1 - (ss_res / (ss_tot + 1e-8))

    # KGE

    covariance = (sum_y_y_hat / count) - (mu_y * mu_y_hat)
    r = covariance / (std_y * std_y_hat + 1e-8)

    # Bias (beta) and Variability (alpha)
    beta = mu_y_hat / (mu_y + 1e-8)
    alpha = std_y_hat / (std_y + 1e-8)

    kge = 1 - np.sqrt((r - 1)**2 + (beta - 1)**2 + (alpha - 1)**2)

    return r2, kge



